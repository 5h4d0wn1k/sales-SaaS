import { z } from "zod";
import {
  dashboardResponseSchema,
  type DashboardResponse,
  type LeadRecord,
  type MeetingRecord,
} from "./domain";

export const meetingCalendarProviderSchema = z.enum(["google", "outlook", "office365"]);

export const meetingCalendarLinkSchema = z.object({
  provider: meetingCalendarProviderSchema,
  label: z.string(),
  href: z.string().url(),
});

export const meetingCalendarHandoffResponseSchema = z.object({
  surface: z.literal("meeting-calendar-handoff"),
  version: z.string(),
  generatedAt: z.string(),
  ready: z.boolean(),
  blockers: z.array(z.string()),
  workspace: z.object({
    name: z.string(),
    planKey: z.string(),
  }),
  meeting: z.object({
    id: z.string(),
    leadId: z.string(),
    status: z.string(),
    scheduledFor: z.string(),
    durationMinutes: z.number().int().positive(),
    owner: z.string(),
    title: z.string(),
    description: z.string(),
    location: z.string(),
    attendeeEmail: z.string().email().nullable(),
    attendeePhone: z.string().nullable(),
    leadName: z.string(),
    company: z.string().nullable(),
  }),
  links: z.array(meetingCalendarLinkSchema),
  ics: z.object({
    filename: z.string(),
    contentType: z.literal("text/calendar; charset=utf-8"),
    content: z.string(),
  }).nullable(),
  guardrails: z.array(z.string()),
  unavailableClaims: z.array(z.string()),
});

export type MeetingCalendarHandoffResponse = z.infer<typeof meetingCalendarHandoffResponseSchema>;

const calendarReadyStatuses = new Set<MeetingRecord["status"]>(["pending", "scheduled"]);
const defaultDurationMinutes = 30;

function parseTimestamp(value: string) {
  const timestamp = Date.parse(value);
  return Number.isNaN(timestamp) ? null : timestamp;
}

function sanitizeFilename(value: string) {
  const normalized = value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

  return normalized || "meeting";
}

function calendarDate(value: Date) {
  return value.toISOString().replace(/[-:]/g, "").replace(/\.\d{3}Z$/, "Z");
}

function escapeIcsText(value: string) {
  return value
    .replace(/\\/g, "\\\\")
    .replace(/\r?\n/g, "\\n")
    .replace(/,/g, "\\,")
    .replace(/;/g, "\\;");
}

function lineFold(value: string) {
  const chunks: string[] = [];
  let remaining = value;

  while (remaining.length > 72) {
    chunks.push(remaining.slice(0, 72));
    remaining = ` ${remaining.slice(72)}`;
  }

  chunks.push(remaining);
  return chunks.join("\r\n");
}

function encodeQuery(input: Record<string, string>) {
  const params = new URLSearchParams();
  for (const [key, value] of Object.entries(input)) {
    params.set(key, value);
  }
  return params.toString();
}

function leadLabel(lead: LeadRecord | undefined) {
  return lead?.fullName ?? "Unknown lead";
}

function meetingTitle(workspaceName: string, lead: LeadRecord | undefined) {
  return `Sales meeting: ${leadLabel(lead)} - ${workspaceName}`;
}

function meetingDescription(input: {
  workspaceName: string;
  lead: LeadRecord | undefined;
  meeting: MeetingRecord;
}) {
  const lines = [
    `Workspace: ${input.workspaceName}`,
    `Lead: ${leadLabel(input.lead)}`,
    input.lead?.company ? `Company: ${input.lead.company}` : null,
    input.lead?.email ? `Email: ${input.lead.email}` : null,
    input.lead?.phone ? `Phone: ${input.lead.phone}` : null,
    `Owner: ${input.meeting.owner}`,
    `Status: ${input.meeting.status}`,
    "",
    input.meeting.notes || "Review lead context and outcome notes in Winrate.",
    "",
    "Generated by Winrate as a manual calendar handoff. This does not auto-contact the lead.",
  ].filter((line): line is string => line !== null);

  return lines.join("\n");
}

function buildIcsContent(input: {
  meeting: MeetingRecord;
  title: string;
  description: string;
  location: string;
  generatedAt: string;
  start: Date;
  end: Date;
}) {
  const status = input.meeting.status === "scheduled" ? "CONFIRMED" : "TENTATIVE";
  const lines = [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//Winrate//Sales Meeting Handoff//EN",
    "CALSCALE:GREGORIAN",
    "METHOD:PUBLISH",
    "BEGIN:VEVENT",
    `UID:${escapeIcsText(input.meeting.id)}@winrate.local`,
    `DTSTAMP:${calendarDate(new Date(input.generatedAt))}`,
    `DTSTART:${calendarDate(input.start)}`,
    `DTEND:${calendarDate(input.end)}`,
    `SUMMARY:${escapeIcsText(input.title)}`,
    `DESCRIPTION:${escapeIcsText(input.description)}`,
    `LOCATION:${escapeIcsText(input.location)}`,
    `STATUS:${status}`,
    "END:VEVENT",
    "END:VCALENDAR",
  ];

  return `${lines.map(lineFold).join("\r\n")}\r\n`;
}

function calendarLinks(input: {
  title: string;
  description: string;
  location: string;
  start: Date;
  end: Date;
}) {
  const googleDates = `${calendarDate(input.start)}/${calendarDate(input.end)}`;
  const google = `https://calendar.google.com/calendar/render?${encodeQuery({
    action: "TEMPLATE",
    text: input.title,
    dates: googleDates,
    details: input.description,
    location: input.location,
  })}`;
  const outlookParams = encodeQuery({
    path: "/calendar/action/compose",
    rru: "addevent",
    subject: input.title,
    startdt: input.start.toISOString(),
    enddt: input.end.toISOString(),
    body: input.description,
    location: input.location,
  });

  return [
    {
      provider: "google" as const,
      label: "Google Calendar",
      href: google,
    },
    {
      provider: "outlook" as const,
      label: "Outlook",
      href: `https://outlook.live.com/calendar/0/deeplink/compose?${outlookParams}`,
    },
    {
      provider: "office365" as const,
      label: "Office 365",
      href: `https://outlook.office.com/calendar/0/deeplink/compose?${outlookParams}`,
    },
  ];
}

export function buildMeetingCalendarHandoff(input: {
  dashboard: DashboardResponse;
  meetingId: string;
  generatedAt?: string;
  durationMinutes?: number;
}): MeetingCalendarHandoffResponse | null {
  const dashboard = dashboardResponseSchema.parse(input.dashboard);
  const meeting = dashboard.meetings.find((entry) => entry.id === input.meetingId);
  if (!meeting) {
    return null;
  }

  const generatedAt = input.generatedAt ?? new Date().toISOString();
  const durationMinutes = input.durationMinutes ?? defaultDurationMinutes;
  const lead = dashboard.leads.find((entry) => entry.id === meeting.leadId);
  const timestamp = parseTimestamp(meeting.scheduledFor);
  const blockers = [
    ...(calendarReadyStatuses.has(meeting.status)
      ? []
      : [`Meeting status is ${meeting.status}; calendar handoff is only available for pending or scheduled meetings.`]),
    ...(timestamp === null ? ["Meeting scheduled time is invalid or missing."] : []),
  ];
  const title = meetingTitle(dashboard.workspace.workspaceName, lead);
  const description = meetingDescription({
    workspaceName: dashboard.workspace.workspaceName,
    lead,
    meeting,
  });
  const location = lead?.phone ? `Phone: ${lead.phone}` : "Online or phone";
  const start = timestamp === null ? null : new Date(timestamp);
  const end = start ? new Date(start.getTime() + durationMinutes * 60 * 1000) : null;
  const ready = blockers.length === 0 && start !== null && end !== null;
  const links = ready
    ? calendarLinks({
        title,
        description,
        location,
        start,
        end,
      })
    : [];
  const ics =
    ready && start && end
      ? {
          filename: `${sanitizeFilename(`${leadLabel(lead)}-${meeting.id}`)}.ics`,
          contentType: "text/calendar; charset=utf-8" as const,
          content: buildIcsContent({
            meeting,
            title,
            description,
            location,
            generatedAt,
            start,
            end,
          }),
        }
      : null;

  return meetingCalendarHandoffResponseSchema.parse({
    surface: "meeting-calendar-handoff",
    version: "2026-06-04.meeting-calendar-handoff",
    generatedAt,
    ready,
    blockers,
    workspace: {
      name: dashboard.workspace.workspaceName,
      planKey: dashboard.subscription.planKey,
    },
    meeting: {
      id: meeting.id,
      leadId: meeting.leadId,
      status: meeting.status,
      scheduledFor: meeting.scheduledFor,
      durationMinutes,
      owner: meeting.owner,
      title,
      description,
      location,
      attendeeEmail: lead?.email ?? null,
      attendeePhone: lead?.phone ?? null,
      leadName: leadLabel(lead),
      company: lead?.company ?? null,
    },
    links,
    ics,
    guardrails: [
      "Calendar handoff is operator-triggered and does not auto-contact the lead.",
      "No calendar provider credentials are stored or used by this handoff.",
      "Meeting outcome, reminders, and provider sync still require operator action or future configured integrations.",
    ],
    unavailableClaims: [
      "Autonomous scheduling, calendar-provider sync, reminders, and lead attendance guarantees are not available.",
    ],
  });
}
